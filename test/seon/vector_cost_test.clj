(ns seon.vector-cost-test
  "Cost proofs of semantic search's parts that grow with the store: a search reads every coarse
  row once and only its shortlist's whole vectors; what is due reads each text's and vector's
  facts once."
  (:refer-clojure :exclude [defn defn-])
  (:require [clojure.test :refer [deftest]] [clojure.java.shell] [seon.contract :refer [defn defn-]] [seon.cost :as cost]
            [datahike.api :as d] [my.test :as mt] [seon.db :as pdb] [seon.vector :as vector] [seon.context :as context]))

(def ^:private decay
  "The dims' weights, falling off as a Matryoshka model's do."
  (delay (mapv (fn [i] (Math/exp (/ (- i) 96.0))) (range 768))))

(def ^:private unit-vector-of
  "A seed's unit vector, made once: the sizes of a proof share their forms' seeds, so a vector is made
  once for all of them, not once a size."
  (memoize
    (fn [seed]
      (let [a (* (inc seed) 0.37)
            v (mapv (fn [w i] (* w (Math/sin (* a (inc i))))) @decay (range 768))
            n (Math/sqrt (reduce (fn [s x] (+ s (* x x))) 0.0 v))]
        (mapv #(/ % n) v)))))

(defn- unit-vector
  "A unit vector of 768 dims, seeded, its weight falling off along the dims as a Matryoshka
  model's does."
  {:malli/schema [:=> [:cat :int] [:vector number?]]}
  [seed]
  (unit-vector-of seed))

(def ^:private form-tx
  "Form i's transaction data (the form and its vector's fact), made once: the sizes of a proof, and
  the proofs, share their forms, and packing a 768-dim vector is the dearest part of making one."
  (memoize
    (fn [i] [{:db/id (str "f" i) :form/id (str "vf" i) :form/src (str "(defn vf" i " [])")}
             (vector/fact (str "f" i) 0 (unit-vector i) 8 "m")])))

(def ^:private grown
  "{n db}: the stores store-of made, so the next, a larger one, adds only the forms past the largest
  smaller one (the dearest part of a proof is adding a vector's facts to a db, once for each form of each
  size, where a size ascending from the last adds each form once). A cache, regenerated by store-of."
  (atom {}))

(defn- store-of
  "The world with n forms added, each with its vector."
  {:malli/schema [:=> [:cat pos-int?] :seon.host/db]}
  [n]
  (let [m (reduce max 0 (filter #(<= % n) (keys @grown)))
        db (mt/with (if (pos? m) (@grown m) (mt/world)) (vec (mapcat form-tx (range m n))))]
    (swap! grown assoc n db)
    db))

(defn near-of
  "seon.vector/near's arguments: n forms with vectors, a query vector, k 10, and a shortlist of 10 (the
  rerank's size, which the claim holds for at any value: a small one puts every size past it)."
  {:malli/schema [:=> [:cat pos-int?] [:tuple :seon.host/db [:vector number?] :int [:map [:shortlist pos-int?]]]]}
  [n] [(store-of n) (unit-vector 100003) 10 {:shortlist 10}])

(deftest a-search-reads-each-row-once
  ;; the claim: a search reads each coarse row once (linear in the store) and reranks a shortlist of constant size.
  ;; The shortlist is 10 here (:shortlist, not config's 400), so sizes of 30 to 300 are all past it. Red if a row is
  ;; read twice or the rerank grows with the store (the per-row bytes and ticks rise over :per-n).
  (cost/proof
    {:of 'seon.vector/near :input 'seon.vector-cost-test/near-of
     :n "vectors in the store, past the shortlist of 10 (below it every vector is the shortlist)"
     :work (str "every coarse row read from its datom and copied once into the kernel's buffer and one C scan "
                "of them (linear in n), then the shortlist's whole vectors read and ranked: the opts' :shortlist (10) "
                "of them, a constant")
     :growth :linear
     ;; measured 2026-10-23 in the full run: 1.24M ticks / 5.92 MB at 500, 1.32M / 6.18 MB at 1,000,
     ;; 1.50M / 6.85 MB at 2,000: ~173 ticks and 620 B a coarse row; below the shortlist (all rows
     ;; reranked) 0.33M / 1.6 MB at 100, ~2,900 ticks and 14 KB a reranked row, so the 400 reranked
     ;; rows are most of the fixed part (set below it: a fixed part near the smallest size's whole
     ;; cost reads as steeper growth)
     ;; 2026-10-29 (a-vector-is-its-own-entity): the join of each coarse row to the entity it embeds is a merge
     ;; join with the scan of :seon.vector/of, one datom read more a row: 5.22 MB at 1,000 (from 5.16), inside these
     ;; 2026-10-31 (shrink-tests-4): shortlist 10, sizes [30 100 300] on the world: 74k ticks / 275 KB at 30, 105k / 332 KB at 100,
     ;; 189k / 466 KB at 300: ~430 ticks and ~700 B a coarse row, the fixed part (the 10 reranked rows, the kernel's setup)
     ;; ~62k / 250 KB. With config's shortlist of 400 the reranked rows were 1M of the fixed part and sizes had to pass 400
     :per-n {:ticks 440.0 :bytes 750.0}
     :fixed {:ticks 62000.0 :bytes 250000.0}
     :sizes [30 100 300]}))

(defn due-of
  "seon.vector/due's arguments: n forms, every one with its vector, of another model than asked,
  so each is read and each is due."
  {:malli/schema [:=> [:cat pos-int?] [:tuple :seon.host/db :string]]}
  [n] [(store-of n) "m2"])

(deftest what-is-due-reads-each-fact-once
  (cost/proof
    {:of 'seon.vector/due :input 'seon.vector-cost-test/due-of
     :n "texts in the store"
     :work (str "the vectors' text transactions and models, one index scan each into a map, then each text's "
                "datom once with two lookups, and one sort of what is due (n log n, the scans dominate)")
     :growth :linear
     ;; measured 2026-10-23: 0.25M ticks / 1.5 MB at 100, 0.43M / 2.6 MB at 300, 0.98M / 6.1 MB at
     ;; 1,000 (the seed's own texts are the fixed part): ~790 ticks and 5 KB a text. 2026-10-27:
     ;; 0.48M / 2.92 MB at 100, the titles (seon.vector/titles: one scan each of the vars' names and
     ;; forms, the sections' headings and the schema keys, mostly the seed's) a fixed ~1.5 MB more
     ;; 2026-10-31 (shrink-tests-4): on the world (seon.vector-cost-test/store-of), which holds no seed texts and no
     ;; titles to scan: 65k ticks / 259 KB at 30, 143k / 622 KB at 100, 355k / 1.68 MB at 300: ~1,060 ticks and
     ;; 5.3 KB a text, the fixed part ~40k / 100 KB (the 1.5 MB of titles was the seed's)
     :per-n {:ticks 1100.0 :bytes 5500.0}
     :fixed {:ticks 40000.0 :bytes 100000.0}
     :sizes [30 100 300]}))

(defn similar-of
  "seon.context/similar's arguments: n forms with vectors and none a function, so it ranks every
  one and walks every rank (its worst case); the query one of them, nothing named."
  {:malli/schema [:=> [:cat pos-int?] [:tuple :seon.host/db :int [:set :qualified-symbol]]]}
  [n] (let [db (store-of n)
            ;; each form defines a test, so every rank's vars are read and none is a function
            db (d/db-with db (vec (for [i (range n)] {:var/name (symbol "vc-test" (str "t" i)) :var/kind :test :var/form [:form/id (str "vf" i)]})))
            q (:e (first (d/datoms db :avet :form/id "vf0")))]
        ;; the query asks for five (its own setting, as a task's :seon.task/config is: off by default)
        [(d/db-with db [{:db/id q :seon.config.render/similar 5}]) q #{}]))

(deftest similar-ranks-every-form-once
  ;; the owner's ruling (2026-10-24, DECISIONS "Embeddings join the context"): :similar is an
  ;; exact search, measured
  (cost/proof
    {:of 'seon.context/similar :input 'seon.vector-cost-test/similar-of
     :n "forms with vectors"
     :work (str "near with every vector its shortlist at every dim (each coarse row and each whole vector "
                "read once, one C scan and one C rerank of all of them, one sort), then each rank's form's "
                "vars read until :seon.config.render/similar functions are found (here none: every rank)")
     :growth :n-log-n
     ;; 2026-10-31 (shrink-tests-4): on the world, sizes [10 30 100]: 184k ticks / 856 KB at 10, 439k / 1.67 MB at 30,
     ;; 1.37M / 4.63 MB at 100: ~1,800 ticks and 5.7 KB a form n log n unit, the fixed part ~125k / 670 KB
     ;; (the seed's forms and the 400-row shortlist's share were in the 300k / 1.5 MB the larger sizes held)
     :per-n {:ticks 2000.0 :bytes 6000.0}
     :fixed {:ticks 150000.0 :bytes 750000.0}
     :sizes [10 30 100]}))

;; A store on disk of this test's own, the last resort (docs/storage.md): the in-memory test store gives
;; its index nodes no addresses, so no two db values of it share a stored subtree and a structural diff
;; of them reads everything (as in seon.merge-cost-test); main's dbs are LMDB's, which share them.
(def ^:private store
  (delay (:conn (pdb/open! :lmdb (str (seon.config/checkout) "/target/vector-cost-" (random-uuid)) 0 :db))))

(defn round-of
  "seon.vector/vectors-proc's arguments for main's notice of a commit that wrote one form, with n
  forms in the store, every one due (a vector of another text's transaction), and the proc caught up
  at the db before the commit: the one text is the only one looked at."
  {:malli/schema [:=> [:cat pos-int?] [:tuple :map :keyword :map]]}
  [n]
  (let [conn @store
        cfg (pdb/store-cfg :lmdb (get-in @conn [:config :store :path]))
        b (keyword (str "r" n "-" (random-uuid)))
        _ (d/branch! conn :db b)
        bc (d/connect (assoc cfg :branch b))
        _ (d/transact bc {:tx-data (vec (mapcat form-tx (range n)))})
        s (keyword (str (name b) "-next"))
        _ (d/branch! conn b s)
        c (d/connect (assoc cfg :branch s))
        _ (d/transact c {:tx-data [{:form/id "vnew" :form/src "(defn vnew [])"}]})
        ;; the previous round read the clean commit's db (it asked for what was due there), so root's node cache
        ;; holds its nodes when this round diffs from it: read them here, as that round did
        _ (vector/due (d/commit-as-db c (d/commit-id (pdb/head conn b))) "m")
        r [(assoc (vector/vectors-proc {:model "m" :texts 64 :conn c}) :clean {:t 0 :commit (d/commit-id (pdb/head conn b))} :seen (d/commit-id (pdb/head conn b))) :main {:t 1 :commit (d/commit-id (pdb/head conn s))}]]
    (d/release bc)
    r))

(deftest a-commit-is-embedded-for-what-it-changed
  (try
    (cost/proof
      {:of 'seon.vector/vectors-proc :input 'seon.vector-cost-test/round-of
       :n "texts in the store, one written by the commit"
       :work (str "the commit's text datoms (datoms-diff skips every subtree the two dbs share: log n) and, "
                  "for each, one seek of its vector's facts: not a scan of every text")
       :growth :linear
       ;; measured 2026-10-27 on LMDB: 127k ticks / 245 KB / 8 calls at 100 texts, 162k / 273 KB at 300, 178k / 366 KB
       ;; at 1,000 (the leaves datoms-diff reads grow slowly with the store): ~60 ticks and ~140 bytes a text, where
       ;; a scan of every text read ~790 ticks and 5 KB a text (what-is-due-reads-each-fact-once)
       ;; 2026-10-27: 130k / 263 KB / 12 calls at 100: the written text's title by seeks (seon.vector/title,
       ;; its stored read), two contracted calls more
       ;; 2026-10-29 (vectors-clean-is-a-commit): the round makes its dbs from commits (seon.db/at-commit), where it held
       ;; them: 130k ticks / 263 KB / 12 calls became 287k / 961 KB / 14 calls at 100. Measured apart: the notice's
       ;; commit is the conn's head (a deref and the contract: 55k / 238 KB), the :clean commit is made from the store
       ;; (datahike commit-as-db, 97k / 440 KB, steady state: its cost is the store's read of the commit, not a cold cache),
       ;; the diff itself unchanged (121k / 229 KB). Size-independent; the price of not pinning a version of the index
       ;; 2026-10-29 (a-vector-is-its-own-entity): the written text's vector is found through :seon.vector/of
       ;; (seon.vector/vector-e), one contracted call and seek more: 301k / 1.01 MB / 15 calls at 100
       :per-n {:ticks 70.0 :bytes 150.0}
       :fixed {:ticks 310000.0 :bytes 1000000.0 :calls 15}
       :sizes [30 100 300]})
    (finally (when (realized? store)
               (let [path (get-in @@store [:config :store :path])]
                 (d/release @store) (clojure.java.shell/sh "rm" "-rf" path))))))
