(require '[datahike.api :as d] '[datahike.db :as db] '[datahike.query :as q])
(defn both [database query & args]
  (into {} (for [[k dis] [[:planner false] [:base true]]]
             [k (try (binding [q/*disable-planner* dis q/*query-result-cache?* false] (set (apply d/q query database args)))
                     (catch Throwable e (str "ERROR " (.getMessage e))))])))
(def chain (d/db-with (db/empty-db {:p/friend {:db/valueType :db.type/ref}} {:keep-history? true})
                      [{:db/id 1} {:db/id 2 :p/friend 1} {:db/id 3 :p/friend 2}]))
(def reach '[[(reach ?a ?b) [?a :p/friend ?b]] [(reach ?a ?b) [?a :p/friend ?x] (reach ?x ?b)]])
(prn :F3-reach-self (both chain '[:find ?a :in $ % :where (reach ?a ?a)] reach))
(prn :F3-nonrec-self (both chain '[:find ?a :in $ % :where (edge ?a ?a)] '[[(edge ?a ?b) [?a :p/friend ?b]]]))
(def tagdb (d/db-with (db/empty-db {:t/tags {:db/cardinality :db.cardinality/many} :t/n {}} {:keep-history? true})
                      [{:db/id 1 :t/tags ["tag1" "x"] :t/n 1} {:db/id 2 :t/tags ["x"] :t/n 7}]))
(prn :F4-added-false-current (both tagdb '[:find ?e ?t :where [?e :t/tags ?t ?tx false]]))
(prn :F4-added-false-asof (both (d/as-of tagdb (:max-tx tagdb)) '[:find ?e ?t :where [?e :t/tags ?t ?tx false]]))
(prn :F6-fn-binds-bound-var (both tagdb '[:find ?e ?v :where [?e :t/tags ?v] [?e :t/n ?n] [(str "tag" ?n) ?v]]))
(def pair (d/db-with (db/empty-db {:p/id {:db/unique :db.unique/identity}
                                   :p/pair {:db/valueType :db.type/tuple :db/tupleTypes [:db.type/keyword :db.type/long]}})
                     [{:db/id 1 :p/id "a" :p/pair [:k1 1]} {:db/id 2 :p/id "b" :p/pair [:k2 2]}]))
(def rules '[[(has-pair ?e ?p) [?e :p/pair ?p]] [(same ?x ?y) [(= ?x ?y)]]])
(prn :F1-tuple-literal (both pair '[:find ?e :in $ % :where (has-pair ?e [:k1 1])] rules))
(prn :F1-tuple-input (both pair '[:find ?e :in $ % ?p :where (has-pair ?e ?p)] rules [:k1 1]))
(prn :F2-lookup-as-value (both pair '[:find ?e :in $ % :where [?e :p/id "a"] (same ?e [:p/id "a"])] rules))
(def tagdb2 (d/db-with (db/empty-db {:t/tags {:db/cardinality :db.cardinality/many} :t/n {}} {:keep-history? true})
                      [{:db/id 1 :t/tags ["tag1" "x"] :t/n 0} {:db/id 2 :t/tags ["x"] :t/n 7}]))
(def later (d/db-with tagdb2 [[:db/retract 1 :t/tags "x"]]))
(prn :F4-join-current (both later '[:find ?e ?t :where [?e :t/tags ?t ?tx false] [?e :t/n 0]]))
(prn :F4-join-current-rev (both later '[:find ?e ?t :where [?e :t/n 0] [?e :t/tags ?t ?tx false]]))
(prn :F4-join-current-true (both later '[:find ?e ?t :where [?e :t/tags ?t ?tx true] [?e :t/n 0]]))
(prn :F4-join-history (both (d/history later) '[:find ?e ?t :where [?e :t/tags ?t ?tx false] [?e :t/n 0]]))
(def chain2 (d/db-with (db/empty-db {:p/friend {:db/valueType :db.type/ref}} {:keep-history? true})
                      [{:db/id 1} {:db/id 2 :p/friend 1} {:db/id 3 :p/friend 2} {:db/id 4 :p/friend 4}]))
(prn :pattern-self (both chain2 '[:find ?a :where [?a :p/friend ?a]]))
(prn :nonrec-self (both chain2 '[:find ?a :in $ % :where (edge ?a ?a)] '[[(edge ?a ?b) [?a :p/friend ?b]]]))
(prn :nonrec-self-bound (both chain2 '[:find ?a :in $ % :where [?a :p/friend _] (edge ?a ?a)] '[[(edge ?a ?b) [?a :p/friend ?b]]]))
(prn :reach-self (both chain2 '[:find ?a :in $ % :where (reach ?a ?a)] '[[(reach ?a ?b) [?a :p/friend ?b]] [(reach ?a ?b) [?a :p/friend ?x] (reach ?x ?b)]]))
(System/exit 0)
