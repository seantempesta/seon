(require '[datahike.api :as d] '[seon.cluster.store :as store])
(def memory-config {:store {:backend :memory :id (java.util.UUID/randomUUID)}
                    :schema-flexibility :write :keep-history? true})
(d/create-database memory-config)
(def mem-conn (d/connect memory-config))
(def installed-schema (into [] (map (fn [[_ a]] (dissoc a :db/id))) (d/schema @user/file-conn)))
(println :ATTRS (count installed-schema))
(d/transact mem-conn installed-schema)
(d/transact mem-conn [{:seon.cluster.agent/id "root"}])
(def mem-root (d/q '[:find ?e . :where [?e :seon.cluster.agent/id "root"]] @mem-conn))
(println :MEM-HISTORY (pr-str (user/quantiles (user/timed 100 2000 (fn [i] (store/transact! mem-conn (user/message-row mem-root i)))))))
(def nh-config {:store {:backend :memory :id (java.util.UUID/randomUUID)}
                :schema-flexibility :write :keep-history? false})
(d/create-database nh-config)
(def nh-conn (d/connect nh-config))
(d/transact nh-conn installed-schema)
(d/transact nh-conn [{:seon.cluster.agent/id "root"}])
(def nh-root (d/q '[:find ?e . :where [?e :seon.cluster.agent/id "root"]] @nh-conn))
(println :MEM-NOHISTORY (pr-str (user/quantiles (user/timed 100 2000 (fn [i] (store/transact! nh-conn (user/message-row nh-root i)))))))
(println :DB3-DONE)
