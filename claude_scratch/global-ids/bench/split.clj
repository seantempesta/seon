;; root's writer ops by kind, on Seon's own src+test as main's program, one ~55-datom turn on a branch
(require '[datahike.api :as d] '[seon.db :as pdb] '[seon.source :as source] '[seon.merge :as pm] '[seon.program-test :as pt] 'clojure.java.shell)
(defn ms [t0] (/ (- (System/nanoTime) t0) 1e6))
(defmacro timed [label n & body] `(let [_# (do ~@body) t0# (System/nanoTime)] (dotimes [_# ~n] ~@body) (println (format "%-44s %9.2f ms" ~label (/ (ms t0#) ~n)))))
(def root "/Users/sean/src/seon-jolt/next-global-ids")
(def path (str root "/target/m/split"))
(clojure.java.shell/sh "rm" "-rf" path)
(def files (into {} (for [dir ["src" "test"] f (file-seq (java.io.File. (str root "/" dir)))
                          :when (and (.isFile f) (.endsWith (.getName f) ".clj"))]
                      [(subs (.getPath f) (inc (count root))) (slurp f)])))
(def o (pdb/open! :lmdb path 0 :db))
(def conn (:conn o))
(def t0 (System/nanoTime))
(d/transact conn {:tx-data (source/import-tx @conn files) :tx-meta (pdb/tx-meta)})
(println "imported" (count files) "files in" (format "%.0f ms;" (ms t0)) "live forms" (count (seon.program/live-forms @conn)) "datoms" (count (d/datoms @conn :eavt)))
(def cfg (:cfg o))
(d/branch! conn :db :b)
(def bc (d/connect (assoc cfg :branch :b)))
;; one turn: a redefinition recorded as the agent records it, and its turn's platform facts
(d/transact bc {:tx-data (seon.program/record-tx @bc (#'pt/eval-account 'seon.fixtures "(defn generation [] 2)")) :tx-meta (pdb/tx-meta)})
(d/transact bc {:tx-data (vec (for [i (range 40)] {:note/text (str "turn fact " i)})) :tx-meta (pdb/tx-meta)})
(pdb/sync! cfg)
(def base (pdb/branch-base conn :db :b)) (def head (pdb/head conn :b)) (def main @conn)
(println "branch delta datoms" (let [[g a] (d/datoms-diff base head :eavt [])] (+ (count g) (count a))))
(println "---- before (land14: whole programs)")
(timed "seon.merge/program, one db" 3 (pm/program head #{}))
(timed ":branch-diff / merge decision (3 programs)" 2 (pm/three-way (pm/program base #{}) (pm/program head #{}) (pm/program main #{})))
(println "---- after (jolt/global-ids: deltas)")
(timed "delta-three-way (:branch-diff, merge decision)" 10 (pm/delta-three-way base head main #{}))
(timed "unmerged (entry keys only)" 10 (pm/unmerged head))
(let [r (pm/delta-three-way base head main #{})]
  (println "  ours keys" (vec (keys (:ours r))))
  (timed "merge-tx (verbatim datoms)" 10 (pm/merge-tx main base head (keys (:ours r)) #{}))
  (let [tx (pm/merge-tx main base head (keys (:ours r)) #{})
        t1 (System/nanoTime) rep (d/merge-db conn #{:b} tx (pdb/tx-meta))]
    (println (format "%-44s %9.2f ms (%d datoms)" "d/merge-db commit of the carried datoms" (ms t1) (count (:tx-data rep))))))
(timed "d/transact, 55 datoms on main" 5 (d/transact conn {:tx-data (vec (for [i (range 55)] {:note/text (str "main fact " (rand))})) :tx-meta (pdb/tx-meta)}))
(timed "d/transact, 1 datom on main" 5 (d/transact conn {:tx-data [{:note/text (str "one " (rand))}] :tx-meta (pdb/tx-meta)}))
(timed "sync (LMDB env sync)" 5 (pdb/sync! cfg))
(timed "d/branch! (spawn)" 5 (d/branch! conn :db (keyword (str "s" (rand-int 1000000)))))
(clojure.java.shell/sh "rm" "-rf" path)
