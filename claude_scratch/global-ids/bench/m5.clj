;; a verbatim merge (the branch's own datoms, their e/a/v/tx kept) against today's re-transact (seon.merge)
(require '[datahike.api :as d] '[seon.db :as pdb] '[seon.merge :as pm])
(def path "/Users/sean/src/seon-jolt/next-global-ids/target/m/big")
(def cfg (assoc (pdb/store-cfg :lmdb path) :store-cache-size 200000))
(def conn (d/connect cfg))
(defn ms [t0] (/ (- (System/nanoTime) t0) 1e6))
(def stamp (str (System/currentTimeMillis)))
(defn fresh-main [nm] (let [b (keyword (str nm "-" stamp))] (d/branch! conn :db b) (d/connect (assoc cfg :branch b))))
(pdb/preload! @conn)
;; today's: three programs, three-way, apply-tx, merge commit
(let [mc (fresh-main "re") b :b0
      t0 (System/nanoTime)
      base (pdb/branch-base mc :db b) head (pdb/head mc b)
      t-open (ms t0)
      pb (pm/program base #{}) ph (pm/program head #{}) pmn (pm/program @mc #{})
      t-prog (ms t0)
      r (pm/three-way pb ph pmn)
      changed (into {} (for [[k [_ ov]] (:ours r)] [k ov]))
      tx (pm/apply-tx @mc changed)
      t-tx (ms t0)
      rep (d/merge-db mc #{b} tx (pdb/tx-meta))
      t-all (ms t0)]
  (println "re-transact: keys" (count changed) "tx-data" (count tx) "datoms written" (count (:tx-data rep))
           (format "open %.1f programs %.1f three-way+apply-tx %.1f commit %.1f total %.1f ms" t-open (- t-prog t-open) (- t-tx t-prog) (- t-all t-tx) t-all))
  (println "  new form eids on main == branch's?" (= (set (map :e (d/datoms head :aevt :form/order))) (set (map :e (d/datoms (:db-after rep) :aevt :form/order))))))
;; verbatim: the branch's datoms since the base, as Datoms
(let [mc (fresh-main "vb") b :b1
      t0 (System/nanoTime)
      base (pdb/branch-base mc :db b) head (pdb/head mc b)
      t-open (ms t0)
      [gone added] (d/datoms-diff base head :eavt [])
      t-diff (ms t0)
      tx (vec (concat (map #(datahike.datom/datom (:e %) (:a %) (:v %) (:tx %) false) gone) added))
      rep (d/merge-db mc #{b} tx (pdb/tx-meta))
      t-all (ms t0)
      after (:db-after rep)]
  (println "verbatim: datoms carried" (count tx) "datoms written" (count (:tx-data rep))
           (format "open %.1f diff %.1f commit %.1f total %.1f ms" t-open (- t-diff t-open) (- t-all t-diff) t-all))
  (println "  txs of carried datoms on main" (sort (distinct (map :tx (filter #(= :form/src (:a %)) (:tx-data rep)))))
           "merge tx" (:max-tx after) "main max-tx before" (:max-tx @(d/connect (assoc cfg :branch :db))))
  (println "  carried == branch datoms?" (= (set (map (juxt :e :a :v :tx) added))
                                            (set (map (juxt :e :a :v :tx) (filter :added (:tx-data rep))))))
  (println "  extra datoms written beyond the carried:" (remove (set (map (juxt :e :a :v :tx :added) tx)) (map (juxt :e :a :v :tx :added) (:tx-data rep)))))
