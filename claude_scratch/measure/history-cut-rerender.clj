(require '[datahike.api :as d] '[seon.db :as pdb] '[seon.context :as context] '[seon.print.select :as select] '[seon.config :as cfg] '[clojure.string :as str])
(def scfg (pdb/store-cfg :lmdb "STORE"))
(def c0 (d/connect scfg))
(def b (first (filter #(str/includes? (str %) "a-map") (d/branches c0))))
(def c (d/connect (assoc scfg :branch b)))
(def db @c)
(def ts (sort (d/q '[:find ?n ?e ?tx :in $ ?r :where [?ru :seon.run/id ?r] [?e :seon.turn/run ?ru] [?e :seon.turn/origin :model] [?e :seon.turn/n ?n ?tx]] db "seon.print/a-map-shows-its-first-entry#2")))
(def tok (fn [ms] (select/estimate (apply str (mapcat (fn [m] (cons (:content m) (map :code (:tool-calls m)))) ms)))))
(def before (mapv (fn [[n e]] (into [] (mapcat second) (context/parts-of db (:seon.turn/sent (d/pull db [:seon.turn/sent] e))))) ts))
(def head (subvec (first before) 0 2))
(def agent-e (:db/id (d/entity db [:seon.agent/key (:agent (:seon.turn/basis (d/pull db [:seon.turn/basis] (second (first ts)))))])))
(def all-records (context/records db agent-e))
(defn request-at [tx]
  (let [rs (filterv (fn [[t]] (< t tx)) all-records)
        cache (#'context/printed-run (mapv (fn [[t v k]] [(#'context/ref-of v) v k t]) rs) nil)
        parts (mapv #(get-in cache [:parts %]) (:ids cache))
        [picks dropped] (#'context/kept parts (cfg/value :seon.config.render/history-budget))
        whole-ids (into #{} (keep (fn [[{:keys [ref]} pick]] (when (= :whole pick) (second ref)))) (map vector (drop dropped parts) picks))
        sent (mapv (fn [{:keys [ref collapsed] :as p} pick] (if (= :line pick) collapsed (second (#'context/as-sent p whole-ids)))) (drop dropped parts) picks)]
    (into (cond-> head (pos? dropped) (conj {:role "user" :content (pr-str {:history {:left-out dropped}})})) (mapcat identity) sent)))
(def after (mapv (fn [[n e tx]] (request-at tx)) ts))
(defn share [reqs] (let [pairs (partition 2 1 reqs)
                         shared (reduce + (for [[a b] pairs :let [k (count (take-while true? (map = a b)))]] (tok (subvec b 0 k))))
                         total (reduce + (map tok (rest reqs)))]
                     {:turns (count reqs) :tokens-per-turn (quot (reduce + (map tok reqs)) (count reqs)) :shared-share (double (/ shared total))
                      :breaks (count (filter (fn [[a b]] (< (count (take-while true? (map = a b))) (count a))) pairs))}))
(println "before" (share before))
(println "after " (share after))
